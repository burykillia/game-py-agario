from math import hypot
from socket import socket, AF_INET, SOCK_STREAM
from pygame import *
from threading import Thread
from random import randint
from launcher import ConnectWindow

# Показуємо GUI-вікно (окреме, напевно на tkinter) для введення імені гравця,
# адреси хоста та порту сервера. Код зупиняється тут, поки вікно не закриють.
win = ConnectWindow()
win.mainloop()

# Дістаємо введені користувачем дані з об'єкта вікна після його закриття
name = win.name
port = win.port
host = win.host

# Створюємо TCP-сокет (SOCK_STREAM = TCP, надійна передача з гарантованим порядком)
# і одразу підключаємось до сервера гри
sock = socket(AF_INET, SOCK_STREAM)
sock.connect((host, port))

# Одразу після підключення сервер надсилає стартовий пакет (до 64 байт):
# рядок виду "id,x,y,radius", розділений комами.
# Розбираємо його в список чисел.
my_data = list(map(int, sock.recv(64).decode().strip().split(',')))
my_id = my_data[0]         # унікальний ідентифікатор, присвоєний сервером цьому клієнту
my_player = my_data[1:]    # [x, y, radius] - поточний стан власного гравця

# Переводимо сокет у неблокуючий режим: recv() тепер не зупиняє програму,
# якщо даних немає, а одразу кидає виняток. Це потрібно, бо recv буде
# викликатись у нескінченному циклі окремого потоку і не повинен його "заморожувати"
sock.setblocking(False)

# Ініціалізація pygame та створення вікна гри 1000x1000 пікселів
init()
window = display.set_mode((1000, 1000))
clock = time.Clock()             # для контролю FPS
f = font.Font(None, 50)          # великий шрифт для напису про поразку
name_font = font.Font(None, 20)  # дрібний шрифт для підписів імен гравців

all_players = []  # сюди потік receive_data буде класти актуальний список усіх гравців з сервера
running = True     # прапорець головного циклу гри
lose = False        # прапорець "гравець програв" (наприклад, його з'їли)


def receive_data():
    """
    Функція виконується в окремому потоці паралельно з основним циклом рендерингу.
    Постійно (поки running=True) намагається прочитати дані від сервера
    і оновлює глобальний список гравців, щоб основний цикл міг їх намалювати.
    Винесено в окремий потік, бо мережеві операції не повинні блокувати відмальовку кадрів.
    """
    global all_players, running, lose
    while running:
        try:
            # Читаємо до 4096 байт - за раз сервер може прислати дані одразу про кількох гравців
            data = sock.recv(4096).decode().strip()

            if data == "LOSE":
                # Сервер повідомляє, що цього гравця з'їли / він програв
                lose = True
            elif data:
                # Протокол: гравці розділені символом '|',
                # усередині кожного - "id,x,y,radius,name" через кому.
                # strip('|') прибирає зайвий роздільник на краях рядка (якщо є)
                parts = data.strip('|').split('|')

                # Для кожного шматка беремо перші 4 частини як числа (id, x, y, radius),
                # а 5-ту (ім'я) залишаємо рядком і додаємо в кінець списку.
                # Фільтр len(p.split(',')) == 5 відкидає "биті"/неповні пакети,
                # які могли прийти через розрив TCP-повідомлення на межі буфера
                all_players = [list(map(int, p.split(',')[:4])) + [p.split(',')[4]] for p in parts if
                               len(p.split(',')) == 5]

                print(all_players)  # дебаг-вивід поточного стану гравців у консоль
        except:
            # Найчастіше сюди потрапляємо, коли даних ще немає (неблокуючий сокет)
            # або через тимчасову мережеву помилку. Просто пропускаємо ітерацію.
            pass


# daemon=True означає, що потік автоматично завершиться разом з головною програмою,
# навіть якщо не встигне коректно завершити свій цикл
Thread(target=receive_data, daemon=True).start()


class Eat:
    """Об'єкт їжі на карті - маленьке кольорове коло, яке гравець з'їдає, щоб рости."""
    def __init__(self, x, y, r, c):
        self.x = x           # координата X у "світових" координатах (не екранних!)
        self.y = y           # координата Y у світових координатах
        self.radius = r
        self.color = c

    def check_collision(self, player_x, player_y, player_r):
        # Класична перевірка перетину двох кіл: відстань між центрами
        # менша або дорівнює сумі радіусів -> є зіткнення.
        # hypot(dx, dy) рахує відстань швидше й точніше, ніж sqrt(dx**2+dy**2)
        dx = self.x - player_x
        dy = self.y - player_y
        return hypot(dx, dy) <= self.radius + player_r


# Генеруємо 300 одиниць їжі у випадкових точках великої "світової" карти (-2000..2000),
# набагато більшої за розмір вікна - тому і потрібна камера/масштабування нижче
eats = [Eat(randint(-2000, 2000), randint(-2000, 2000), 10,
            (randint(0, 255), randint(0, 255), randint(0, 255)))
        for _ in range(300)]

# ===================== Головний ігровий цикл =====================
while running:
    # Обробка системних подій pygame (закриття вікна тощо)
    for e in event.get():
        if e.type == QUIT:
            running = False

    window.fill((255, 255, 255))  # білий фон - "очищення" кадру перед новим малюванням

    # Масштаб камери залежить від розміру власного гравця:
    # чим гравець більший (my_player[2] - його радіус), тим менший масштаб (карта "віддаляється"),
    # щоб великий гравець і оточення вміщались на екрані.
    # min(...) обмежує максимальне наближення (1.5), max(...) - мінімальне віддалення (0.3)
    scale = max(0.3, min(50 / my_player[2], 1.5))

    # Малюємо всіх інших гравців. Координати переводяться зі "світових" в екранні:
    # беремо різницю між позицією гравця і власного персонажа (це і є принцип камери,
    # прив'язаної до гравця), множимо на масштаб і зсуваємо в центр вікна (+500, тому що
    # вікно 1000x1000 і центр знаходиться в точці 500,500)
    for p in all_players:
        if p[0] == my_id: continue  # самого себе малюємо окремо нижче
        sx = int((p[1] - my_player[0]) * scale + 500)
        sy = int((p[2] - my_player[1]) * scale + 500)
        draw.circle(window, (255, 0, 0), (sx, sy), int(p[3] * scale))
        name_text = name_font.render(f'{p[4]}', 1, (0, 0, 0))
        window.blit(name_text, (sx, sy))  # підпис імені прямо над/на колі гравця

    # Власний гравець завжди малюється рівно в центрі екрана (500, 500),
    # оскільки камера "прив'язана" саме до нього - це і створює ефект руху світу навколо
    draw.circle(window, (0, 255, 0), (500, 500), int(my_player[2] * scale))

    # Перевірка з'їдання їжі: якщо колізія є - позначаємо об'єкт на видалення
    # і збільшуємо радіус гравця пропорційно розміру з'їденої їжі.
    # Якщо колізії немає - малюємо цю їжу на екрані (з тим самим переведенням координат камери)
    to_remove = []
    for eat in eats:
        if eat.check_collision(my_player[0], my_player[1], my_player[2]):
            to_remove.append(eat)
            my_player[2] += int(eat.radius * 0.2)  # ріст гравця
        else:
            sx = int((eat.x - my_player[0]) * scale + 500)
            sy = int((eat.y - my_player[1]) * scale + 500)
            draw.circle(window, eat.color, (sx, sy), int(eat.radius * scale))

    # Видаляємо з'їдену їжу зі списку окремо від циклу вище,
    # щоб не змінювати список eats під час ітерації по ньому (це викликало б помилку/пропуски)
    for eat in to_remove:
        eats.remove(eat)

    # Якщо сервер повідомив про поразку - показуємо напис поверх усього іншого
    if lose:
        t = f.render('U lose!', 1, (244, 0, 0))
        window.blit(t, (400, 500))

    display.update()   # виводимо намальований кадр на екран
    clock.tick(60)      # обмежуємо швидкість циклу до 60 разів на секунду (60 FPS)

    if not lose:
        # Рух дозволений, тільки якщо гравець ще живий.
        # key.get_pressed() повертає стан усіх клавіш на момент виклику,
        # тому можлива одночасна діагональна ходьба (наприклад W+D)
        keys = key.get_pressed()
        if keys[K_w]: my_player[1] -= 15   # вгору (зменшення Y)
        if keys[K_s]: my_player[1] += 15   # вниз
        if keys[K_a]: my_player[0] -= 15   # вліво
        if keys[K_d]: my_player[0] += 15   # вправо

        # Надсилаємо серверу свій новий стан у форматі "id,x,y,radius,name",
        # щоб сервер міг розіслати ці дані іншим підключеним клієнтам
        try:
            msg = f"{my_id},{my_player[0]},{my_player[1]},{my_player[2]},{name}"
            sock.send(msg.encode())
        except:
            # Якщо сокет тимчасово не готовий до запису (неблокуючий режим) -
            # просто пропускаємо цей кадр відправки, наступного разу спробуємо знову
            pass

quit()  # коректне завершення роботи pygame після виходу з головного циклу